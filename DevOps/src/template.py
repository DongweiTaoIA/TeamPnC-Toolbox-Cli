"""Generate a rollout backlog template from a completed numbered sequence.

The DW accounting model rollout was executed twice with the same numbered steps:
DW2 used 501-572 and DW3/Honda used 601-672, matching 54 out of 54 with no gaps.
That makes the sequence a proven playbook, so the next OEM rollout can be
generated instead of designed from scratch.

Usage:
    python src/template.py --name "DW4 Toyota" --base 700
    python src/template.py --name "DW4 Toyota" --base 700 --out templates/dw4.md
"""

import argparse
import collections
import json
import re
import sqlite3
import sys

from common import DB_PATH as DB, ROOT

# Titles look like:
#   (EP): DW Accounting Model - New DW2 AM - 501 - Data upload 1 (1 table) - cfGLProgramGroup
# Everything up to and including the step number is boilerplate; the rest is the
# step's actual description and is what carries over to the next rollout.
TITLE_PREFIX = re.compile(
    r"^\s*\(EP\):\s*DW Accounting Model\s*-\s*New DW\d+ AM\s*-\s*\d{3}\s*-\s*",
    re.I,
)

# The step numbers cluster into phases. Ranges are on the DW2 (5xx) numbering.
PHASES = [
    (501, 529, "Data upload", "Load and validate source data, table by table."),
    (530, 549, "Transaction types", "Premium, cancellation, claims, cash and suspense handling."),
    (550, 554, "Reports", "The DPR316x / DPR318x report family."),
    (555, 559, "WebAPI", "Service layer endpoints."),
    (560, 569, "UI", "Screens."),
    (570, 599, "Close-out", "Scripts, regression testing and aging reports."),
]


def phase_of(step):
    for lo, hi, name, blurb in PHASES:
        if lo <= step <= hi:
            return name, blurb
    return "Other", ""


def load_pairs(conn):
    """Find numbered steps that were executed in both the 5xx and 6xx rollouts."""
    rows = conn.execute(
        "select id, title, state, sprint from tickets "
        "where in_scope=1 and type in ('Requirement','Bug','Feature')"
    ).fetchall()

    steps = {}
    for wid, title, state, sprint in rows:
        m = re.search(r"\b(\d{3})\b", title or "")
        if m:
            steps.setdefault(int(m.group(1)), []).append((wid, title or "", state, sprint))

    pairs = []
    for n in sorted(steps):
        if 500 <= n <= 599 and n + 100 in steps:
            dw2 = steps[n][0]
            dw3 = steps[n + 100][0]
            pairs.append(
                {
                    "step": n,
                    "desc": TITLE_PREFIX.sub("", dw2[1]).strip(),
                    "dw2_id": dw2[0],
                    "dw2_sprint": dw2[3],
                    "dw3_id": dw3[0],
                    "dw3_sprint": dw3[3],
                }
            )
    return pairs


def evidence(conn, pairs):
    ids = [p["dw2_id"] for p in pairs] + [p["dw3_id"] for p in pairs]
    if not ids:
        return {}
    qm = ",".join("?" * len(ids))
    out = collections.defaultdict(dict)
    for tid, kind, n in conn.execute(
        f"select ticket_id, kind, count(*) from links "
        f"where ticket_id in ({qm}) group by ticket_id, kind",
        ids,
    ):
        out[tid][kind] = n
    return out


def ev_label(ev, tid):
    d = ev.get(tid) or {}
    bits = []
    if d.get("tfvc"):
        bits.append(f"{d['tfvc']} changeset" + ("s" if d["tfvc"] > 1 else ""))
    if d.get("git_commit"):
        bits.append(f"{d['git_commit']} commit" + ("s" if d["git_commit"] > 1 else ""))
    if d.get("attachment"):
        bits.append(f"{d['attachment']} attachment" + ("s" if d["attachment"] > 1 else ""))
    return ", ".join(bits) if bits else "-"


def render(pairs, ev, name, base):
    org = "https://dev.azure.com/SOPCV-SNW/DP_Unifi_NEW/_workitems/edit"
    L = []
    A = L.append

    A(f"# {name} rollout - generated backlog template")
    A("")
    A(f"Generated by `src/template.py` from the DW2 (501-572) and DW3/Honda (601-672) rollouts.")
    A("")
    A(
        f"Those two rollouts ran the **same {len(pairs)} numbered steps, matching "
        f"{len(pairs)} out of {len(pairs)} with no gaps**. The sequence below renumbers that "
        f"proven playbook to the {base + 1}-{base + (pairs[-1]['step'] - 500)} range for "
        f"**{name}**."
    )
    A("")
    A("Each row links the DW2 and DW3 tickets that already did the step, so whoever picks it "
      "up can read exactly how it was done last time before starting.")
    A("")

    A("## How to use this")
    A("")
    A("1. Review the step list - drop any step that does not apply to this OEM, and note the reason.")
    A("2. Create the work items using the generated titles.")
    A("3. On each new ticket, paste the **Reference** links into the description.")
    A("4. Keep the ordering. The phases below are sequential; steps within a phase can often run in parallel.")
    A("")

    A("## Phases")
    A("")
    for lo, hi, pname, blurb in PHASES:
        n = sum(1 for p in pairs if lo <= p["step"] <= hi)
        if n:
            A(f"- **{pname}** ({n} steps) - {blurb}")
    A("")

    cur = None
    for p in pairs:
        pname, _ = phase_of(p["step"])
        if pname != cur:
            cur = pname
            A("")
            A(f"## {pname}")
            A("")
            A("| New step | Title | DW2 ref | DW3 ref | Prior evidence |")
            A("|---|---|---|---|---|")
        new_step = base + (p["step"] - 500)
        title = f"({name}): {p['desc']}" if p["desc"] else f"({name}): step {new_step}"
        ev_txt = " / ".join(
            x for x in [ev_label(ev, p["dw2_id"]), ev_label(ev, p["dw3_id"])] if x != "-"
        ) or "none"
        A(
            f"| {new_step} | {title} | [{p['dw2_id']}]({org}/{p['dw2_id']}) "
            f"(S{p['dw2_sprint']}) | [{p['dw3_id']}]({org}/{p['dw3_id']}) "
            f"(S{p['dw3_sprint']}) | {ev_txt} |"
        )

    A("")
    A("## Caveats")
    A("")
    A("- Step descriptions are copied from DW2 and still name DW2-specific tables and reports. "
      "Re-read each one against the new OEM before committing to it.")
    A("- The PAT used for collection lacks **Code: Read**, so the changeset counts above are "
      "link counts only - file lists and diffs were not retrieved. Re-run `src/collect.py` with "
      "a Code: Read token to deepen the references.")
    A("- This is a starting backlog, not a commitment. Sizing and sequencing still need a human.")
    A("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--name", default="DW4", help="name of the next rollout, e.g. 'DW4 Toyota'")
    ap.add_argument("--base", type=int, default=700, help="base step number (700 -> 701..772)")
    ap.add_argument("--out", help="output path (default templates/<name>-rollout.md)")
    ap.add_argument("--json", action="store_true", help="also write the step list as JSON")
    args = ap.parse_args()

    if not DB.exists():
        sys.exit(f"No database at {DB}. Run src/collect.py first.")

    conn = sqlite3.connect(DB)
    pairs = load_pairs(conn)
    if not pairs:
        sys.exit("No paired 5xx/6xx steps found. Collect the DW2 and DW3 sprints first.")

    ev = evidence(conn, pairs)
    text = render(pairs, ev, args.name, args.base)

    slug = re.sub(r"[^a-z0-9]+", "-", args.name.lower()).strip("-")
    out = ROOT / (args.out or f"templates/{slug}-rollout.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"Wrote {out}  ({len(pairs)} steps, {args.base + 1}-{args.base + pairs[-1]['step'] - 500})")

    if args.json:
        jp = out.with_suffix(".json")
        for p in pairs:
            p["new_step"] = args.base + (p["step"] - 500)
        jp.write_text(json.dumps(pairs, indent=2), encoding="utf-8")
        print(f"Wrote {jp}")


if __name__ == "__main__":
    main()
